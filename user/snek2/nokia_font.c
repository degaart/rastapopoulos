const NokiaGlyph* nokia_glyph(NokiaFont font, unsigned char ch)
{
    if ((unsigned)font > 3)
        font = NOKIA_SMALL_PLAIN;
    if (ch < 32 || ch > 126)
        ch = 32;
    return &glyphs[font][ch - 32];
}
int nokia_text_width(NokiaFont font, const char* text)
{
    int width = 0;
    for (; *text; text++)
        width += nokia_glyph(font, (unsigned char)*text)->width;
    return width;
}
